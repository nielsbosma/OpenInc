function nf(lang: ExportLang) {
  const f = new Intl.NumberFormat(lang === 'sv' ? 'sv-SE' : 'en-GB', { maximumFractionDigits: 10 });
  return (v: bigint | string | number) => f.format(typeof v === 'string' ? Number(v) : v);
}

const rangesText = (rs: { from: bigint; to: bigint }[]) => rs.map((r) => (r.from === r.to ? `${r.from}` : `${r.from}–${r.to}`)).join(', ');

async function header(ctx: Ctx) {
  const status = await run(registryStatus, ctx, {});
  if (!status.setUp) throw badRequest('The share register is not set up yet');
  const company = await getSettings('company');
  return { status, settings: status.settings, companyName: company?.name ?? 'Company' };
}

function footerText(lang: ExportLang, companyName: string, lastHash: string | null) {
  const t = L[lang];
  const stamp = new Date().toISOString().slice(0, 16).replace('T', ' ');
  return `${companyName} · ${t.generated} ${stamp} UTC${lastHash ? ` · ${t.lastTx} ${lastHash.slice(0, 16)}` : ''}`;
}

async function lastHash(ctx: Ctx): Promise<string | null> {
  const history = await run(registryHistory, ctx, {});
  const last = [...history.items].sort((a, b) => (b.seq ?? 0) - (a.seq ?? 0))[0];
  return last?.hash ?? null;
}

async function logExport(ctx: Ctx, what: string, details: Record<string, unknown>) {
  await audit(ctx, { action: 'registry.export', entityType: 'registry', after: { what, ...details } });
}

export async function registerExport(ctx: Ctx, input: { asOf?: string; format: 'pdf' | 'xlsx' | 'csv'; lang: ExportLang }): Promise<ExportFile> {
  const { settings, companyName } = await header(ctx);
  const view = await run(getRegister, ctx, { asOf: input.asOf });
  const t = L[input.lang];
  const n = nf(input.lang);
  const money = (v: bigint) => formatMoney(v, view.currency, input.lang === 'sv' ? 'sv-SE' : 'en-GB');
  const base = `share-register-${view.asOf}`;
  await logExport(ctx, 'register', { asOf: view.asOf, format: input.format });
  const restrictionText = (r: { consent: boolean; preEmption: boolean; firstRefusal: boolean }) =>
    [r.consent && t.consent, r.preEmption && t.preEmption, r.firstRefusal && t.firstRefusal].filter(Boolean).join(', ') || t.noRestrictions;

  if (input.format === 'csv') return { filename: `${base}.csv`, contentType: 'text/csv; charset=utf-8', body: Buffer.from(`﻿${registerCsv(view)}`) };

  const holderRows = view.holders.flatMap((h) =>
    h.positions.map((p) => ({
      [t.holder]: h.name,
      [t.id]: h.nationalId,
      [t.address]: h.address,
      [t.class]: p.classCode,
      [t.count]: Number(p.count),
      [t.numbers]: rangesText(p.ranges),
      [t.note]: [p.interim && t.interim, p.pledged ? `${n(p.pledged)} ${t.pledged}` : ''].filter(Boolean).join(', '),
      [t.capitalPct]: Number(h.capitalPct),
      [t.votesPct]: Number(h.votesPct),
    })),
  );

  if (input.format === 'xlsx') {
    const wb = XLSX.utils.book_new();
    const summary = [
      [t.company, companyName],
      [t.nationalNumber, settings.nationalNumber],
      [t.asOf, view.asOf],
      [t.shareCapital, Number(view.shareCapital) / 10 ** currencyDigits(view.currency)],
      [t.shares, Number(view.totalShares)],
      [t.votes, Number(view.totalVotes)],
      [t.quota, Number(view.quotaValue)],
    ];
    XLSX.utils.book_append_sheet(wb, XLSX.utils.aoa_to_sheet(summary), t.register.slice(0, 31));
    XLSX.utils.book_append_sheet(wb, XLSX.utils.json_to_sheet(holderRows), t.holders.slice(0, 31));
    XLSX.utils.book_append_sheet(
      wb,
      XLSX.utils.json_to_sheet(
        view.classes.map((c) => ({
          [t.class]: c.code,
          [t.votesPerShare]: Number(c.votesPerShare),
          [t.issued]: Number(c.issued),
          [t.restrictions]: restrictionText(c.restrictions),
        })),
      ),
      t.classes.slice(0, 31),
    );
    if (view.pledges.length)
      XLSX.utils.book_append_sheet(
        wb,
        XLSX.utils.json_to_sheet(
          view.pledges.map((p) => ({
            [t.holder]: view.holders.find((h) => h.holderId === p.holderId)?.name ?? '',
            [t.class]: p.classCode,
            [t.count]: Number(p.count),
            [t.numbers]: rangesText(p.ranges),
            [t.pledgee]: p.pledgee.name,
            [t.since]: p.since,
          })),
        ),
        t.pledges.slice(0, 31),
      );
    return {
      filename: `${base}.xlsx`,
      contentType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
      body: XLSX.write(wb, { type: 'buffer', bookType: 'xlsx' }) as Buffer,
    };
  }

  const pdf = new PdfWriter(footerText(input.lang, companyName, await lastHash(ctx)), { landscape: true, title: t.register });
  pdf.title(`${t.register} – ${companyName}`, `${t.asOf} ${view.asOf}`);
  pdf.facts([
    [t.company, companyName],
    [t.nationalNumber, settings.nationalNumber],
    [t.shareCapital, money(view.shareCapital)],
    [t.shares, n(view.totalShares)],
    [t.votes, n(view.totalVotes)],
    [t.quota, `${n(view.quotaValue)} ${view.currency}`],
  ]);
  if (!settings.rulePackInfo.countrySpecific) pdf.paragraph(t.noCountryChecks);
  pdf.heading(t.classes);
  pdf.table(
    [
      { header: t.class, width: 2 },
      { header: t.votesPerShare, width: 2, align: 'right' },
      { header: t.issued, width: 2, align: 'right' },
      { header: t.capitalPct, width: 2, align: 'right' },
      { header: t.votesPct, width: 2, align: 'right' },
      { header: t.restrictions, width: 4 },
    ],
    view.classes.map((c) => [c.code, n(c.votesPerShare), n(c.issued), n(c.capitalPct), n(c.votesPct), restrictionText(c.restrictions)]),
  );
  pdf.heading(t.holders);
  pdf.table(
    [
      { header: t.holder, width: 4 },
      { header: t.id, width: 3, mono: true },
      { header: t.address, width: 4 },
      { header: t.class, width: 1.3 },
      { header: t.count, width: 2, align: 'right' },
      { header: t.numbers, width: 4, mono: true },
      { header: t.capitalPct, width: 1.8, align: 'right' },
      { header: t.votesPct, width: 1.8, align: 'right' },
      { header: t.note, width: 2.5 },
    ],
    view.holders.flatMap((h) =>
      h.positions.map((p, i) => [
        i === 0 ? h.name : '',
        i === 0 ? h.nationalId : '',
        i === 0 ? h.address : '',
        p.classCode,
        n(p.count),
        rangesText(p.ranges),
        i === 0 ? n(h.capitalPct) : '',
        i === 0 ? n(h.votesPct) : '',
        [p.interim && t.interim, p.pledged ? `${n(p.pledged)} ${t.pledged}` : ''].filter(Boolean).join(', '),
      ]),
    ),
  );
  if (view.pledges.length) {
    pdf.heading(t.pledges);
    pdf.table(
      [
        { header: t.holder, width: 4 },
        { header: t.class, width: 1.5 },
        { header: t.count, width: 2, align: 'right' },
        { header: t.numbers, width: 4, mono: true },
        { header: t.pledgee, width: 4 },
        { header: t.since, width: 2 },
      ],
      view.pledges.map((p) => [
        view.holders.find((h) => h.holderId === p.holderId)?.name ?? '',
        p.classCode,
        n(p.count),
        rangesText(p.ranges),
        p.pledgee.name,
        p.since,
      ]),
    );
  }
  pdf.paragraph(t.kept);
  pdf.signatureLines(t.signatures);
  return { filename: `${base}.pdf`, contentType: 'application/pdf', body: await pdf.finish() };
}

export async function historyExport(ctx: Ctx, input: { format: 'pdf' | 'xlsx' | 'csv'; lang: ExportLang }): Promise<ExportFile> {
  const { companyName, settings } = await header(ctx);
  const history = await run(registryHistory, ctx, {});
  const register = await run(getRegister, ctx, { asOf: '9999-12-31' });
  const t = L[input.lang];
  const n = nf(input.lang);
  const names = new Map<string, string>();
  for (const item of history.items) for (const h of item.transaction.holders) names.set(h.holderId, h.name);
  for (const h of register.holders) names.set(h.holderId, h.name);
  const typeLabel = (type: string) => (input.lang === 'sv' ? (SV_TYPES[type] ?? type) : (TRANSACTION_LABELS[type as keyof typeof TRANSACTION_LABELS] ?? type));
  await logExport(ctx, 'history', { format: input.format });
  const rows = history.items.flatMap((item) => {
    const kind = item.transaction.type === 'transfer' ? (input.lang === 'sv' ? SV_TRANSFER[item.transaction.kind] : item.transaction.kind.replace(/_/g, ' ')) : '';
    const label = `${typeLabel(item.type)}${kind ? ` (${kind})` : ''}${item.status === 'reversed' ? ' ✕' : ''}`;
    if (!item.movements.length) return [[String(item.seq), item.effectiveDate, label, '', '', '', '', '', item.summary]];
    return item.movements.map((m, i) => [
      i === 0 ? String(item.seq) : '',
      i === 0 ? item.effectiveDate : '',
      i === 0 ? label : '',
      m.classCode,
      m.fromHolderId ? (names.get(m.fromHolderId) ?? '') : '',
      m.toHolderId ? (names.get(m.toHolderId) ?? '') : '',
      n(m.count),
      m.rangeFrom !== null ? `${m.rangeFrom}–${m.rangeTo}` : '',
      m.consideration !== null ? formatMoney(m.consideration, history.currency) : '',
    ]);
  });
  const headers = [t.seq, t.date, t.type, t.class, t.from, t.to, t.count, t.numbers, t.consideration];
  if (input.format === 'csv') return { filename: 'share-register-history.csv', contentType: 'text/csv; charset=utf-8', body: Buffer.from(`﻿${toCsv([headers, ...rows])}`) };
  if (input.format === 'xlsx') {
    const wb = XLSX.utils.book_new();
    XLSX.utils.book_append_sheet(wb, XLSX.utils.aoa_to_sheet([headers, ...rows]), t.history.slice(0, 31));
    return {
      filename: 'share-register-history.xlsx',
      contentType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
      body: XLSX.write(wb, { type: 'buffer', bookType: 'xlsx' }) as Buffer,
    };
  }
  const pdf = new PdfWriter(footerText(input.lang, companyName, await lastHash(ctx)), { landscape: true, title: t.history });
  pdf.title(`${t.history} – ${companyName}`, settings.nationalNumber);
  pdf.table(
    [
      { header: t.seq, width: 0.8, mono: true },
      { header: t.date, width: 1.8 },
      { header: t.type, width: 3 },
      { header: t.class, width: 1.2 },
      { header: t.from, width: 3.5 },
      { header: t.to, width: 3.5 },
      { header: t.count, width: 1.8, align: 'right' },
      { header: t.numbers, width: 2.5, mono: true },
      { header: t.consideration, width: 2.5, align: 'right' },
    ],
    rows,
  );
  return { filename: 'share-register-history.pdf', contentType: 'application/pdf', body: await pdf.finish() };
}

export async function holderExtract(ctx: Ctx, input: { holderId: string; asOf?: string; lang: ExportLang }): Promise<ExportFile> {
  const { companyName, settings } = await header(ctx);
  const holder = await run(getHolder, ctx, { holderId: input.holderId, asOf: input.asOf });
  const t = L[input.lang];
  const n = nf(input.lang);
  await logExport(ctx, 'holder_extract', { holderId: input.holderId, asOf: holder.asOf });
  const pdf = new PdfWriter(footerText(input.lang, companyName, await lastHash(ctx)), { title: t.holderExtract });
  pdf.title(`${t.holderExtract} – ${companyName}`, `${t.asOf} ${holder.asOf}`);
  pdf.heading(t.details);
  const kind = holder.current.kind;
  pdf.facts([
    [t.holder, holder.current.name],
    [t.id, holder.current.nationalId],
    [t.address, holder.current.address],
    [t.type, input.lang === 'sv' ? SV_KINDS[kind] : kind],
    [t.company, `${companyName} (${settings.nationalNumber})`],
  ]);
  pdf.heading(t.shares);
  pdf.table(
    [
      { header: t.class, width: 2 },
      { header: t.count, width: 2, align: 'right' },
      { header: t.numbers, width: 6, mono: true },
      { header: t.note, width: 3 },
    ],
    (holder.position?.positions ?? []).map((p) => [
      p.classCode,
      n(p.count),
      rangesText(p.ranges),
      [p.interim && t.interim, p.pledged ? `${n(p.pledged)} ${t.pledged}` : ''].filter(Boolean).join(', '),
    ]),
  );
  if (holder.position)
    pdf.facts([
      [t.capitalPct, n(holder.position.capitalPct)],
      [t.votesPct, n(holder.position.votesPct)],
    ]);
  if (holder.pledges.length) {
    pdf.heading(t.pledges);
    pdf.table(
      [
        { header: t.class, width: 2 },
        { header: t.count, width: 2, align: 'right' },
        { header: t.pledgee, width: 5 },
        { header: t.since, width: 2 },
      ],
      holder.pledges.map((p) => [p.classCode, n(p.count), p.pledgee.name, p.since]),
    );
  }
  pdf.signatureLines(t.signatures);
  return { filename: `share-register-extract-${holder.asOf}.pdf`, contentType: 'application/pdf', body: await pdf.finish() };
}

export async function settlementNote(ctx: Ctx, input: { transactionId: string; lang: ExportLang }): Promise<ExportFile> {
  const { companyName, settings } = await header(ctx);
  const tx = await run(getTransaction, ctx, { transactionId: input.transactionId });
  if (tx.transaction.type !== 'transfer') throw badRequest('Settlement notes are for transfers');
  const transfer = tx.transaction;
  const t = L[input.lang];
  const n = nf(input.lang);
  const currency = (await getSettings('company'))?.currency ?? 'EUR';
  const name = (id: string) => tx.holderNames[id] ?? id;
  await logExport(ctx, 'settlement_note', { transactionId: tx.id });
  const pdf = new PdfWriter(footerText(input.lang, companyName, tx.hash), { title: t.settlement });
  pdf.title(`${t.settlement}`, `${companyName} (${settings.nationalNumber})`);
  pdf.facts([
    [t.seller, name(transfer.fromHolderId)],
    [t.buyer, name(transfer.toHolderId)],
    [t.date, transfer.effectiveDate],
    [t.settlementDate, transfer.settlement?.date ?? ''],
    [t.reference, transfer.settlement?.reference ?? (tx.seq ? `#${tx.seq}` : '')],
    [t.price, transfer.pricePerShare !== undefined ? `${n(String(transfer.pricePerShare))} ${currency}` : ''],
  ]);
  let total = 0n;
  pdf.table(
    [
      { header: t.class, width: 2 },
      { header: t.count, width: 2, align: 'right' },
      { header: t.numbers, width: 5, mono: true },
      { header: t.consideration, width: 3, align: 'right' },
    ],
    tx.movements.map((m) => {
      total += m.consideration ?? 0n;
      return [m.classCode, n(m.count), m.rangeFrom !== null ? `${m.rangeFrom}–${m.rangeTo}` : '', m.consideration !== null ? formatMoney(m.consideration, currency) : ''];
    }),
  );
  pdf.facts([[t.total, formatMoney(total, currency)]]);
  if (transfer.settlement?.terms) pdf.paragraph(`${t.terms}: ${transfer.settlement.terms}`);
  pdf.signatureLines(t.sellerSign);
  return { filename: `settlement-note-${tx.seq ?? 'draft'}.pdf`, contentType: 'application/pdf', body: await pdf.finish() };
}

/** Everything needed to rebuild the register elsewhere: settings, every committed transaction with its hash, and the register today. */
export async function fullJsonExport(ctx: Ctx): Promise<ExportFile> {
  const { settings, companyName } = await header(ctx);
  const history = await run(registryHistory, ctx, {});
  const register = await run(getRegister, ctx, {});
  await logExport(ctx, 'full_json', {});
  const body = JSON.stringify(
    {
      format: 'openinc-share-register',
      version: 1,
      exportedAt: new Date().toISOString(),
      company: companyName,
      settings,
      transactions: history.items.map((i) => ({
        id: i.id,
        seq: i.seq,
        status: i.status,
        enteredAt: i.enteredAt,
        hash: i.hash,
        prevHash: i.prevHash,
        rulePackVersion: i.rulePackVersion,
        transaction: i.transaction,
      })),
      register,
    },
    (_k, v) => (typeof v === 'bigint' ? v.toString() : v),
    2,
  );
  return { filename: 'share-register.json', contentType: 'application/json', body: Buffer.from(body) };
}
