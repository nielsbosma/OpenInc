import type { CapTable } from './table.ts';

type Table = CapTable & { definition: string };

const HEADERS = [
  'Stakeholder',
  'Issued',
  'Options and Warrants',
  'Of Which Vested',
  'Virtual Shares',
  'Fully Diluted',
  'Issued %',
  'Fully Diluted %',
  'Votes %',
  'Value',
];

function tableRows(t: Table) {
  const codes = t.classes.map((c) => c.code);
  const header = [HEADERS[0]!, ...codes.map((c) => `Class ${c}`), ...HEADERS.slice(1)];
  const rows = t.rows.map((r) => [
    r.name,
    ...codes.map((c) => Number(r.byClass[c] ?? 0)),
    Number(r.issued),
    Number(r.awards),
    Number(r.vestedAwards),
    Number(r.virtual),
    Number(r.fullyDiluted),
    Number(r.issuedPct),
    Number(r.fullyDilutedPct),
    Number(r.votesPct),
    r.value === null ? '' : Number(r.value) / 10 ** currencyDigits(t.currency),
  ]);
  const total = [
    'Total',
    ...codes.map((c) => Number(t.classes.find((x) => x.code === c)!.issued)),
    Number(t.totals.issued),
    Number(t.totals.awards),
    '',
    Number(t.totals.virtual),
    Number(t.totals.fullyDiluted),
    100,
    100,
    100,
    '',
  ];
  return { header, rows, total };
}

const xlsx = (wb: XLSX.WorkBook) => XLSX.write(wb, { type: 'buffer', bookType: 'xlsx' }) as Buffer;

async function companyName() {
  return (await getSettings('company'))?.name || 'Company';
}

/** The cap table for a date as PDF, XLSX, CSV or JSON. Every format states the fully diluted definition. */
export async function captableExport(
  ctx: Ctx,
  input: { asOf?: string; view?: 'fully_diluted' | 'issued'; format: 'pdf' | 'xlsx' | 'csv' | 'json' },
): Promise<ExportFile> {
  const t = (await run(getCaptable, ctx, { asOf: input.asOf, view: input.view ?? 'fully_diluted' })) as Table;
  await audit(ctx, { action: 'captable.export', entityType: 'captable', after: { asOf: t.asOf, format: input.format } });
  const base = `cap-table-${t.asOf}`;
  const { header, rows, total } = tableRows(t);
  if (input.format === 'json') return { filename: `${base}.json`, contentType: 'application/json', body: Buffer.from(canonicalJson(t)) };
  if (input.format === 'csv')
    return { filename: `${base}.csv`, contentType: 'text/csv; charset=utf-8', body: Buffer.from(`﻿${toCsv([header, ...rows, total])}`) };
  if (input.format === 'xlsx') {
    const wb = XLSX.utils.book_new();
    XLSX.utils.book_append_sheet(
      wb,
      XLSX.utils.aoa_to_sheet([
        [`Cap Table – ${await companyName()}`],
        ['As of', t.asOf],
        ['Currency', t.currency],
        [],
        header,
        ...rows,
        total,
        [],
        [t.definition],
      ]),
      'Cap Table',
    );
    if (t.unpriced.length)
      XLSX.utils.book_append_sheet(
        wb,
        XLSX.utils.aoa_to_sheet([
          ['Holder', 'Profile', 'Amount', 'Valuation Cap'],
          ...t.unpriced.map((u) => [
            u.name,
            u.profile,
            Number(u.amount) / 10 ** currencyDigits(t.currency),
            u.valuationCap ? Number(u.valuationCap) / 10 ** currencyDigits(t.currency) : '',
          ]),
        ]),
        'Convertibles',
      );
    return { filename: `${base}.xlsx`, contentType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', body: xlsx(wb) };
  }
  const name = await companyName();
  const n = (v: string | number) => new Intl.NumberFormat('en-GB', { maximumFractionDigits: 4 }).format(Number(v));
  const pdf = new PdfWriter(`${name} · Generated by OpenInc ${new Date().toISOString().slice(0, 16).replace('T', ' ')} UTC`, {
    landscape: true,
    title: 'Cap Table',
  });
  pdf.title(`Cap Table – ${name}`, `As of ${t.asOf}`);
  pdf.facts([
    ['Fully diluted units', n(t.totals.fullyDiluted)],
    ['Issued units', n(t.totals.issued)],
    ['Price per share', t.price ? `${n(t.price.pricePerShare)} ${t.currency} (${t.price.source}, ${t.price.date})` : 'None recorded'],
  ]);
  pdf.table(
    header.map((h, i) => ({ header: h, width: i === 0 ? 4 : 2, align: i === 0 ? 'left' : 'right' })),
    [...rows, total].map((r) => r.map((v, i) => (i === 0 || v === '' ? String(v) : n(v as number)))),
  );
  pdf.paragraph(t.definition);
  if (t.unpriced.length) {
    pdf.heading('Unpriced Instruments');
    pdf.table(
      [
        { header: 'Holder', width: 4 },
        { header: 'Profile', width: 3 },
        { header: 'Amount', width: 2, align: 'right' },
        { header: 'Valuation Cap', width: 2, align: 'right' },
      ],
      t.unpriced.map((u) => [
        u.name,
        u.profile,
        formatMoney(BigInt(u.amount), t.currency, 'en-GB'),
        u.valuationCap ? formatMoney(BigInt(u.valuationCap), t.currency, 'en-GB') : '',
      ]),
    );
  }
  return { filename: `${base}.pdf`, contentType: 'application/pdf', body: await pdf.finish() };
}

/** A scenario as XLSX (one sheet per step, plus the waterfall) or JSON. */
export async function scenarioExport(ctx: Ctx, input: { scenarioId: string; format: 'xlsx' | 'json' }): Promise<ExportFile> {
  const { scenario, result, currency } = await run(getScenario, ctx, { id: input.scenarioId });
  await audit(ctx, { action: 'captable.export', entityType: 'captable_scenario', entityId: scenario.id, after: { format: input.format } });
  const base = `scenario-${
    scenario.name
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-|-$/g, '') || scenario.id
  }`;
  if (input.format === 'json')
    return { filename: `${base}.json`, contentType: 'application/json', body: Buffer.from(canonicalJson({ scenario, result })) };
  const wb = XLSX.utils.book_new();
  const sheet = (title: string, t: CapTable) => {
    const { header, rows, total } = tableRows(t as Table);
    XLSX.utils.book_append_sheet(wb, XLSX.utils.aoa_to_sheet([[title], [], header, ...rows, total]), title.slice(0, 31));
  };
  sheet('Base', result.base);
  result.steps.forEach((s, i) => {
    const title = `${i + 1} ${SCENARIO_STEP_LABELS[s.kind]}`;
    if (s.result.kind === 'exit') {
      const w = s.result.waterfall;
      const d = 10 ** currencyDigits(currency);
      XLSX.utils.book_append_sheet(
        wb,
        XLSX.utils.aoa_to_sheet([
          ['Exit Value', Number(w.exitValue) / d],
          ['Distributable', Number(w.distributable) / d],
          [],
          ['Stakeholder', 'Preference', 'Participation', 'Total', '%'],
          ...w.rows.map((r) => [r.name, Number(r.preference) / d, Number(r.participation) / d, Number(r.total) / d, Number(r.pct)]),
        ]),
        title.slice(0, 31),
      );
    } else sheet(title, s.table);
  });
  return { filename: `${base}.xlsx`, contentType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', body: xlsx(wb) };
}
